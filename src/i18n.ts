export const DICTS: Record<Lang, Record<Key, string>> = { it, en };

const KEY = 'nebbia-lang';
let lang: Lang = (() => { try { return localStorage.getItem(KEY) === 'en' ? 'en' : 'it'; } catch { return 'it'; } })();

export const getLang = () => lang;
export function setLang(l: Lang) { lang = l; try { localStorage.setItem(KEY, l); } catch { /* private mode */ } }

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return DICTS[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}
